"""
PDF Export — Convert markdown documents to clean, readable PDFs.

Uses fpdf2 for lightweight PDF generation. No heavy dependencies.
Produces properly formatted documents with headings, body text,
code blocks, and bullet points.
"""

from __future__ import annotations

import re
from pathlib import Path

from fpdf import FPDF


class StudioPDF(FPDF):
    """PDF with Agent Studio styling."""

    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=25)

    def header(self):
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, "Generated by Agent Studio", align="R")
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}}", align="C")


def _parse_markdown_line(line: str) -> tuple[str, str]:
    """Return (type, content) for a markdown line."""
    stripped = line.strip()

    if stripped.startswith("# "):
        return "h1", stripped[2:]
    if stripped.startswith("## "):
        return "h2", stripped[3:]
    if stripped.startswith("### "):
        return "h3", stripped[4:]
    if stripped.startswith("#### "):
        return "h4", stripped[5:]
    if stripped.startswith("- ") or stripped.startswith("* "):
        return "bullet", stripped[2:]
    if re.match(r"^\d+\.\s", stripped):
        return "numbered", re.sub(r"^\d+\.\s*", "", stripped)
    if stripped.startswith("```"):
        return "code_fence", stripped[3:]
    if stripped.startswith("> "):
        return "quote", stripped[2:]
    if stripped == "---" or stripped == "***":
        return "hr", ""
    if stripped == "":
        return "blank", ""

    return "text", stripped


def _clean_inline_formatting(text: str) -> str:
    """Remove markdown inline formatting for PDF text."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)  # bold
    text = re.sub(r"\*(.+?)\*", r"\1", text)       # italic
    text = re.sub(r"`(.+?)`", r"\1", text)         # inline code
    text = re.sub(r"\[(.+?)\]\(.+?\)", r"\1", text)  # links
    return text


def markdown_to_pdf(markdown_text: str, output_path: Path, title: str = None) -> Path:
    """Convert markdown text to a formatted PDF document."""
    pdf = StudioPDF()
    pdf.alias_nb_pages()
    pdf.add_page()

    if title:
        pdf.set_font("Helvetica", "B", 22)
        pdf.set_text_color(30, 30, 30)
        pdf.cell(0, 15, _clean_inline_formatting(title), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

    in_code_block = False
    code_lines = []

    for line in markdown_text.splitlines():
        line_type, content = _parse_markdown_line(line)

        # Handle code blocks
        if line_type == "code_fence":
            if in_code_block:
                # End code block — render it
                pdf.set_font("Courier", "", 9)
                pdf.set_fill_color(245, 245, 245)
                pdf.set_text_color(50, 50, 50)
                for code_line in code_lines:
                    pdf.cell(0, 5, f"  {code_line}", new_x="LMARGIN", new_y="NEXT", fill=True)
                pdf.ln(3)
                code_lines = []
                in_code_block = False
            else:
                in_code_block = True
            continue

        if in_code_block:
            code_lines.append(line.rstrip())
            continue

        content = _clean_inline_formatting(content)

        if line_type == "h1":
            pdf.ln(5)
            pdf.set_font("Helvetica", "B", 18)
            pdf.set_text_color(30, 30, 30)
            pdf.cell(0, 12, content, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(3)

        elif line_type == "h2":
            pdf.ln(4)
            pdf.set_font("Helvetica", "B", 15)
            pdf.set_text_color(50, 50, 50)
            pdf.cell(0, 10, content, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)

        elif line_type == "h3":
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(60, 60, 60)
            pdf.cell(0, 8, content, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)

        elif line_type == "h4":
            pdf.ln(2)
            pdf.set_font("Helvetica", "BI", 11)
            pdf.set_text_color(70, 70, 70)
            pdf.cell(0, 7, content, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

        elif line_type == "bullet":
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.cell(8)  # indent
            pdf.cell(5, 6, chr(8226))  # bullet char
            pdf.multi_cell(0, 6, content)

        elif line_type == "numbered":
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.cell(8)
            pdf.multi_cell(0, 6, content)

        elif line_type == "quote":
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(100, 100, 100)
            pdf.cell(10)  # indent
            pdf.multi_cell(0, 6, content)
            pdf.ln(1)

        elif line_type == "hr":
            pdf.ln(3)
            pdf.set_draw_color(200, 200, 200)
            pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
            pdf.ln(3)

        elif line_type == "text":
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.multi_cell(0, 6, content)

        elif line_type == "blank":
            pdf.ln(3)

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    pdf.output(str(output_path))
    return output_path
